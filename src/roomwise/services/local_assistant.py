"""Useful API-free research help, explicitly deterministic rather than model inference."""
import re


def answer_local(request, comparison, ids):
    question=request.question.casefold()
    selected=[r for r in comparison['candidate_results'] if r['candidate_id'] in ids]
    catalog={c['id']:c for c in comparison.get('catalog_snapshot',[])}
    citations=[]
    limitations=['Generated by local rules, not Gemma or Gemini. No web search or resident-review analysis was performed.']
    followups=['Which mandatory charges remain unconfirmed?','What should I ask before signing?']
    kind='general'
    used=[]
    if re.search(r'\b(safe|safety|crime|demographic|reviews?|resident experiences)\b',question):
        answer='I cannot establish neighborhood safety or current property conditions from this evidence. The collected resident reviews remain research-only and are not used in these answers.'
        kind='insufficient_evidence'
    elif re.search(r'\b(installments?|calendar|billing)\b',question):
        answer='An installment is a scheduled payment toward a lease term. It is not automatically a calendar-month total. Confirm the payment count, exact term and all required charges before comparing it with a monthly budget.'
        limitations.append('The billing explanation is general; a signed offer and its payment schedule determine what is owed.')
    elif re.search(r'\b(commut\w*|rout\w*|bus|transit|walk\w*|cycling|drive|classes|schedule)\b',question):
        kind='evidence';lines=[]
        for row in selected:
            name=catalog.get(row['candidate_id'],{}).get('property_name',row['candidate_id'])
            scope='the week containing' if comparison['inputs'].get('routing_scope')=='representative_week' else 'the selected date'
            lines.append(f"{name}: {row['supported_commitments']} of {row['total_commitments']} scheduled meetings have saved supported route evidence for {scope} {comparison['inputs']['route_date']}.")
            citations.extend(row['evidence_ids']);used.append(row['candidate_id'])
        answer='\n\n'.join(lines)+'\n\nMissing estimates do not prove that a trip is impossible. Live-only provider estimates are excluded from saved comparisons. Verify the complete journey and the timetable for your actual travel date.'
        limitations.append('Housing citations identify the compared offers; they do not supply route evidence. Coverage counts come from the saved deterministic comparison.')
    elif re.search(r'\b(cost\w*|fees?|rent|prices?|budget|missing|unknown|shortlist|compar\w*|fit|offers?|options?)\b',question):
        kind='evidence';lines=[]
        for row in selected:
            candidate=catalog.get(row['candidate_id'],{})
            price=candidate.get('offer',{}).get('price',{})
            basis={'per_person':'per person','whole_unit':'for the whole unit','unknown':'with unconfirmed billing basis'}.get(price.get('basis'),'with unconfirmed billing basis')
            period={'installment':'per installment','calendar_month':'per calendar month','other':'with unconfirmed frequency'}.get(price.get('frequency'),'with unconfirmed frequency')
            amount=f"${price['amount']} {basis} {period}" if price.get('amount') is not None else 'No exact reviewed asking price'
            questions=row['hard_conflicts'][:2]+row['unknown_costs'][:3]
            lines.append(candidate.get('property_name',row['candidate_id'])+' — '+candidate.get('offer',{}).get('layout','')+
                         '\n'+amount+'.\nStatus: '+row['fit_state'].replace('_',' ')+'.\n'+ '\n'.join('• '+x for x in questions))
            citations.extend(row['evidence_ids']);used.append(row['candidate_id'])
        answer='\n\n'.join(lines)
        limitations.append('Dated asking prices are not guaranteed available offers or complete costs. Only a few unresolved items are shown here; the comparison contains the full list.')
    elif re.search(r'\b(sign\w*|lease|ask|deposit|checklist|roommate\w*|move\w*)\b',question):
        answer='Before signing, obtain the complete mandatory fee schedule, exact lease dates and payment count, deposit conditions, bedroom arrangement and each roommate’s responsibility. Confirm availability and test your class journey. Keep the answers in writing and use the DormToDoor checklist to track them.'
        limitations.append('These are general questions, not a review of a lease or legal conclusions.')
    else:
        kind='insufficient_evidence'
        answer='The local helper can explain installment billing, summarize your compared offers and missing costs, report route coverage, and suggest before-you-sign questions. This question needs evidence or a model capability that is not available locally.'
    if not selected and kind=='evidence':
        kind='insufficient_evidence';answer='There are no selected comparison results to explain. Load a comparison and shortlist an offer first.'
    return dict(status='complete',input_revision=comparison['input_revision'],provider='local_rules',model_id=None,
                result=dict(answer=answer[:6000],answer_kind=kind,evidence_ids=sorted(set(citations)),
                            candidate_ids=used,limitations=limitations,next_questions=followups),error=None)
